"""Writing a Markdown report about one or more proteins.

Markdown is a simple text format that GitHub (and VS Code's preview)
displays with headings, tables and images.
"""

from __future__ import annotations

import datetime
from pathlib import Path

from protein_analyzer.constants import (
    AMINO_ACID_NAMES,
    C_TERMINUS_PKA,
    N_TERMINUS_PKA,
    NEGATIVE_SIDE_CHAIN_PKA,
    POSITIVE_SIDE_CHAIN_PKA,
)
from protein_analyzer.plot import plot_titration_curves
from protein_analyzer.sequence import ProteinSequence


def write_report(proteins: list[ProteinSequence], report_path: str,
                 ph: float = 7.0) -> Path:
    """Write a Markdown report to <report_path>, plus a titration curve
    image saved next to it.

    Return the path of the image.
    """
    report = Path(report_path)
    image = report.with_name(f"{report.stem}_titration.png")
    plot_titration_curves(proteins, str(image))

    text = build_report(proteins, image.name, ph)
    report.write_text(text, encoding="utf-8")
    return image


def build_report(proteins: list[ProteinSequence], image_name: str,
                 ph: float = 7.0) -> str:
    """Return the full report as Markdown text.

    <image_name> is the titration curve image's file name, which must be in
    the same folder as the report.
    """
    if len(proteins) == 1:
        title = f"# Protein report: {proteins[0].name}"
    else:
        title = f"# Protein report: {len(proteins)} proteins"

    sections = [
        title,
        f"Generated by Protein Analyzer on {datetime.date.today()}.",
        "## Titration curve",
        f"![Titration curve]({image_name})",
    ]
    for protein in proteins:
        sections.append(protein_section(protein, ph))
    sections.append(methods_section())
    return "\n\n".join(sections) + "\n"


def protein_section(protein: ProteinSequence, ph: float = 7.0) -> str:
    """Return the Markdown section for one protein."""
    lines = [f"## {protein.name}", ""]
    if protein.source:
        lines += [f"Source: {protein.source}", ""]

    gravy = protein.gravy()
    nature = "hydrophobic" if gravy > 0 else "hydrophilic"
    lines += [
        "| Property | Value |",
        "|---|---|",
        f"| Length | {len(protein)} residues |",
        f"| Molecular weight | {protein.molecular_weight():,.2f} Da |",
        f"| Isoelectric point (pI) | {protein.isoelectric_point():.2f} |",
        f"| Net charge at pH {ph} | {protein.net_charge(ph):+.2f} |",
        "| Extinction coefficient (280 nm) | "
        f"{protein.extinction_coefficient():,} M⁻¹ cm⁻¹ (all Cys as "
        "cystines); "
        f"{protein.extinction_coefficient(all_cystines=False):,} "
        "(all Cys reduced) |",
        f"| GRAVY | {gravy:.3f} (overall {nature}) |",
        "",
        "### Amino acid composition",
        "",
        "| Amino acid | Count | Percent |",
        "|---|---:|---:|",
    ]
    counts = protein.composition()
    for aa, percent in protein.percent_composition().items():
        lines.append(f"| {AMINO_ACID_NAMES[aa]} ({aa}) | {counts[aa]} "
                     f"| {percent:.1f}% |")

    lines += ["", "### Sequence", "", "```", format_sequence(protein), "```"]
    return "\n".join(lines)


def format_sequence(protein: ProteinSequence, per_line: int = 60) -> str:
    """Return the sequence in blocks of 10, with the position of the first
    residue at the start of each line.

    >>> print(format_sequence(ProteinSequence("A" * 25), per_line=20))
       1 AAAAAAAAAA AAAAAAAAAA
      21 AAAAA
    """
    lines = []
    residues = protein.residues
    for start in range(0, len(residues), per_line):
        chunk = residues[start:start + per_line]
        blocks = [chunk[i:i + 10] for i in range(0, len(chunk), 10)]
        lines.append(f"{start + 1:>4} {' '.join(blocks)}")
    return "\n".join(lines)


def methods_section() -> str:
    """Return a short description of how the values were calculated."""
    side_chains = ", ".join(
        f"{aa} {pka}" for aa, pka in
        {**POSITIVE_SIDE_CHAIN_PKA, **NEGATIVE_SIDE_CHAIN_PKA}.items()
    )
    return "\n".join([
        "## Methods",
        "",
        "- **Molecular weight:** sum of average residue masses plus one "
        "water.",
        "- **Net charge and pI:** Henderson–Hasselbalch equation using EMBOSS "
        f"pKa values (N-terminus {N_TERMINUS_PKA}, C-terminus "
        f"{C_TERMINUS_PKA}, side chains: {side_chains}). The pI is found "
        "by bisection. Other tools use different pKa values, so their pI "
        "may differ.",
        "- **Extinction coefficient:** Pace et al. (1995); Trp 5500, "
        "Tyr 1490, cystine 125 M⁻¹ cm⁻¹.",
        "- **GRAVY:** average Kyte–Doolittle hydropathy.",
    ])
